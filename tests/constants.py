"""Hard-coded weights and linear probes for the 2nd_argmax RNNs.

This file exists so that the tests depend on neither the alg_zoo library nor
network access.

M_{hidden_size}_{seq_len}_* holds one model per name, extracted with:

    from alg_zoo import zoo_2nd_argmax
    model = zoo_2nd_argmax(hidden_size, seq_len)
    W_hh = as_numpy(model.rnn.weight_hh_l0)     # (hidden_size, hidden_size)
    W_hi = as_numpy(model.rnn.weight_ih_l0)     # (hidden_size, 1)

for hidden_size in [2, 3, 4, 5, 6, 8, 16]
and seq_len in [2, 3, 4, 5, 6, 8, 10], the two numbers appearing in the
name in that order.

The one exception is M_16_10_*, which predates this file and comes from
example_2nd_argmax() instead, a different checkpoint of the same shape. The
zoo model of that shape is therefore named ZOO_16_10_* rather than M_16_10_*.

M_{hidden_size}_{seq_len}_PROBE_RELU_{L} is the weight vector of the
relu_{L}_post linear probe, fitted as in profile_linear_probe of
algozoo/figures_16_10.py with seed=42, against the labeling
inputs[1] > inputs[0] and inputs[1] > 0. Layers [0, 1, 2, 3] are covered,
except that a model with seq_len n only has layers 0 .. n - 1, so the shallower
models carry fewer probes. Every probe is fitted with a hard-coded intercept of
0.0, so all their thresholds are 0.0; the extraction asserts this.
M_16_10_PROBE, again the exception, is the relu_1_post probe of the example
model.

All arrays are stored untruncated. Each test truncates them itself.
"""
